def kullanici_pro_mu(email):
    try:
        result = supabase.table("profiles").select("is_pro").eq("email", email).execute()
        if result.data and len(result.data) > 0:
            return result.data[0]["is_pro"]
    except:
        pass
    return False
def soru_hakki_kontrol(email, is_pro):
    from datetime import date
    limit = 50 if is_pro else 10
    bugun = str(date.today())
    try:
        r = supabase.table("profiles").select("daily_count,last_count_date").eq("email", email).execute()
        satir = r.data[0]
        sayi = satir["daily_count"]
        if satir["last_count_date"] != bugun:
            sayi = 0
        if sayi >= limit:
            return False, limit
        supabase.table("profiles").update(
            {"daily_count": sayi + 1, "last_count_date": bugun}
        ).eq("email", email).execute()
        return True, limit
    except Exception:
        return False, limit
